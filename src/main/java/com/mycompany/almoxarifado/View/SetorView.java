    private void tblSetoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSetoresMouseClicked
        int linha = tblSetores.rowAtPoint(evt.getPoint());
        int coluna = tblSetores.columnAtPoint(evt.getPoint());

        if (linha < 0 || coluna < 0) {
            return;
        }

        if (coluna == 4) {
            Long idSetor = Long.valueOf(
                    tblSetores.getValueAt(linha, 0).toString()
            );

            excluirSetor(idSetor);
            return;
        }
        selecionarSetor();
    }//GEN-LAST:event_tblSetoresMouseClicked

