    private void cadastrar() {
        try {
            SetorDTO setor = new SetorDTO();

            setor.setNome(txtNome.getText().trim());
            setor.setDescricao(txtDescricao.getText().trim());
            setor.setAtivo(chkAtivo.isSelected());

            setorService.cadastrar(setor);

            JOptionPane.showMessageDialog(
                    this,
                    "Setor cadastrado com sucesso."
            );

            limparFormulario();
            carregarSetores();

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Validação",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao cadastrar setor.",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

    private void editar() {
        if (idSelecionado == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um setor para editar."
            );
            return;
        }

        try {
            SetorDTO setor = new SetorDTO();

            setor.setIdSetor(idSelecionado);
            setor.setNome(txtNome.getText().trim());
            setor.setDescricao(txtDescricao.getText().trim());
            setor.setAtivo(chkAtivo.isSelected());

            setorService.atualizar(setor);

            JOptionPane.showMessageDialog(
                    this,
                    "Setor atualizado com sucesso."
            );

            limparFormulario();
            carregarSetores();

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Validação",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao atualizar setor.",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

    private void excluirSetor(Long id) {
        try {
            SetorDTO setor = setorService.buscarPorId(id);

            int confirmacao = JOptionPane.showConfirmDialog(
                    this,
                    "Deseja realmente excluir o setor \"" + setor.getNome() + "\"?",
                    "Excluir setor",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE
            );

            if (confirmacao != JOptionPane.YES_OPTION) {
                return;
            }

            setorService.excluir(id);

            JOptionPane.showMessageDialog(
                    this,
                    "Setor excluído com sucesso."
            );

            limparFormulario();
            carregarSetores();

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Validação",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Não foi possível excluir o setor. Existem registros vinculados a ele.",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

    private void limparFormulario() {
        idSelecionado = null;

        txtNome.setText("");
        txtDescricao.setText("");

        chkAtivo.setSelected(true);

        tblSetores.clearSelection();

        btnSalvar.setEnabled(true);
        btnEditar.setEnabled(false);
        btnDesativar.setEnabled(false);

        btnDesativar.setText("Desativar");

        txtNome.requestFocus();
    }

    private void selecionarSetor() {
        int linha = tblSetores.getSelectedRow();

        if (linha < 0) {
            return;
        }

        idSelecionado = Long.valueOf(
                tblSetores.getValueAt(linha, 0).toString()
        );

        txtNome.setText(
                tblSetores.getValueAt(linha, 1).toString()
        );

        Object descricao = tblSetores.getValueAt(linha, 2);

        txtDescricao.setText(
                descricao == null ? "" : descricao.toString()
        );

        String status = tblSetores.getValueAt(linha, 3).toString();

        boolean ativo = status.equalsIgnoreCase("Ativo");

        chkAtivo.setSelected(ativo);

        btnSalvar.setEnabled(false);
        btnEditar.setEnabled(true);
        btnDesativar.setEnabled(true);

        btnDesativar.setText(
                ativo ? "Desativar" : "Ativar"
        );
    }

    private void alterarStatus() {
        if (idSelecionado == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um setor."
            );
            return;
        }

        try {
            SetorDTO setor
                    = setorService.buscarPorId(idSelecionado);

            boolean novoStatus = !setor.isAtivo();

            String acao = novoStatus ? "ativar" : "desativar";

            int confirmacao = JOptionPane.showConfirmDialog(
                    this,
                    "Deseja " + acao + " este setor?",
                    "Confirmação",
                    JOptionPane.YES_NO_OPTION
            );

            if (confirmacao != JOptionPane.YES_OPTION) {
                return;
            }

            setor.setAtivo(novoStatus);

            setorService.atualizar(setor);

            JOptionPane.showMessageDialog(
                    this,
                    novoStatus
                            ? "Setor ativado com sucesso."
                            : "Setor desativado com sucesso."
            );

            limparFormulario();
            carregarSetores();

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Validação",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao alterar status do setor.",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

    private void carregarSetores() {
        try {
            List<SetorDTO> setores = setorService.listarTodos();

            tableModel.setRowCount(0);

            for (SetorDTO setor : setores) {
                tableModel.addRow(new Object[]{
                    setor.getIdSetor(),
                    setor.getNome(),
                    setor.getDescricao(),
                    setor.isAtivo() ? "Ativo" : "Inativo",
                    "Excluir"
                });
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao carregar setores.",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

